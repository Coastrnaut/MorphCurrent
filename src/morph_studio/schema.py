"""Storyboard schema: creative data, never ComfyUI node IDs."""
from __future__ import annotations

from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, model_validator


class StrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid")


class RenderConfig(StrictModel):
    width: int = Field(default=832, ge=256, le=4096, multiple_of=8)
    height: int = Field(default=480, ge=256, le=4096, multiple_of=8)
    generation_fps: int = Field(default=16, ge=1, le=120)
    delivery_fps: int = Field(default=24, ge=1, le=120)
    anchor_profile: str = Field(min_length=1)
    bridge_profile: str = Field(min_length=1)
    master_seed: int = Field(default=0, ge=0)
    max_bridge_frames: int = Field(default=81, ge=5)
    # F23: delivery crops whose safe areas the subject must fit (checked, never applied to renders)
    delivery_crops: list[Literal["16:9", "9:16"]] = Field(default_factory=list)

    @model_validator(mode="after")
    def check_length(self) -> "RenderConfig":
        if (self.max_bridge_frames - 1) % 4:
            raise ValueError("max_bridge_frames must be 4n+1")
        if self.width % 16 or self.height % 16:
            # WanFirstLastFrameToVideo width/height use object_info step 16 (ComfyUI 0.46.0)
            raise ValueError("render width/height must be multiples of 16 for Wan 2.2")
        return self


class Style(StrictModel):
    description: str = Field(min_length=1)
    composition: str = "centered_subject"
    camera: str = "continuous_slow_push"
    palette: list[str] = Field(default_factory=list)
    # F21: id of a versioned style pack in configs/styles (replaces `description` text in prompts)
    pack: str | None = Field(default=None, pattern=r"^[a-z0-9][a-z0-9-]{0,62}$")


class Audio(StrictModel):
    file: str | None = None
    bpm: float | None = Field(default=None, gt=0, le=400)
    beat_offset_seconds: float = 0.0
    synchronization: Literal["none", "beat", "downbeat"] = "none"
    # F15: the owner must confirm they may use the track; MorphCurrent never fetches audio.
    licensed: bool = False

    @model_validator(mode="after")
    def check_file(self) -> "Audio":
        if self.file is not None:
            if "://" in self.file:
                raise ValueError("audio.file must be a local file path, not a URL")
            if not self.licensed:
                raise ValueError("audio.file requires audio.licensed: true (owner confirms the track may be used)")
        return self


class FramingTarget(StrictModel):
    """F23: desired subject centre (fractions of the frame) and size (mean subject extent)."""
    center: tuple[float, float] = (0.5, 0.5)
    tolerance: float = Field(default=0.08, ge=0, le=0.5)
    size: tuple[float, float] = (0.2, 0.8)

    @model_validator(mode="after")
    def check(self) -> "FramingTarget":
        if not all(0 <= v <= 1 for v in (*self.center, *self.size)) or self.size[0] > self.size[1]:
            raise ValueError("framing center/size must be fractions 0-1 with size min <= max")
        return self


class CameraMove(StrictModel):
    """F23: camera move for one bridge. The installed Wan FLF2V workflow has no camera input, so
    ``control: prompt`` (a labelled prompt-only approximation) is the only supported mode."""
    move: Literal["static", "push_in", "pull_out", "pan_left", "pan_right", "tilt_up", "tilt_down",
                  "orbit_left", "orbit_right", "rise"]
    amount: float = Field(default=0.1, ge=0, le=0.5)
    control: Literal["prompt", "graph"] = "prompt"


class Anchor(StrictModel):
    id: str = Field(pattern=r"^[A-Za-z][A-Za-z0-9_-]*$")
    prompt: str = Field(min_length=1)
    negative_prompt: str | None = None
    seed: int | None = Field(default=None, ge=0)
    # independent_t2i: explicit fallback, generated by T2I; ``reference`` (optional) only names
    # the continuity parent for size/review, it is NOT image-conditioned (F04).
    generation: Literal["text_to_image", "reference_edit", "independent_t2i"] = "text_to_image"
    reference: str | None = None
    # F21: per-scene override of style-pack fields (lighting, palette, negative, ...)
    style_override: dict[str, Any] | None = None
    # F19: optional chapter id; anchors of one chapter must be contiguous
    chapter: str | None = Field(default=None, pattern=r"^[A-Za-z0-9][A-Za-z0-9 _.-]{0,62}$")
    # F23: framing target checked against measured anchor geometry (not used for generation)
    framing: FramingTarget | None = None


class Correspondence(StrictModel):
    source: str = Field(min_length=1, max_length=200)
    target: str = Field(min_length=1, max_length=200)


class Choreography(StrictModel):
    """Structured physical transformation plan compiled into bridge prompts (F13)."""
    correspondences: list[Correspondence] = Field(default_factory=list, max_length=8)
    phases: list[str] = Field(default_factory=list, max_length=5)
    camera: Literal["static", "slow_push", "slow_pull", "orbit_left", "orbit_right", "rising"] = "static"
    keep_centered: bool = True
    keep_scale: bool = True
    negative: list[str] = Field(default_factory=list, max_length=20)


class Transition(StrictModel):
    from_anchor: str = Field(alias="from")
    to_anchor: str = Field(alias="to")
    duration_beats: float = Field(gt=0)
    seed: int | None = Field(default=None, ge=0)
    candidates: int = Field(default=1, ge=1, le=10)
    motion: str = "slow_push"
    prompt: str = Field(min_length=1)
    mode: Literal["direct", "camera", "intermediate"] = "direct"
    choreography: Choreography | None = None
    camera: CameraMove | None = None  # F23

    @model_validator(mode="after")
    def one_camera(self) -> "Transition":
        if self.camera and self.choreography and self.choreography.camera != "static":
            raise ValueError("set either transitions[].camera or a non-static choreography.camera, not both")
        return self


class Storyboard(StrictModel):
    schema_version: Literal[1]
    name: str = Field(min_length=1)
    render: RenderConfig
    style: Style
    audio: Audio = Field(default_factory=Audio)
    anchors: list[Anchor] = Field(min_length=2)
    transitions: list[Transition] = Field(min_length=1)

    @model_validator(mode="after")
    def validate_chain(self) -> "Storyboard":
        ids = [a.id for a in self.anchors]
        if len(set(ids)) != len(ids):
            raise ValueError("anchor IDs must be unique")
        for index, anchor in enumerate(self.anchors):
            if anchor.generation == "reference_edit":
                if not anchor.reference or anchor.reference not in ids[:index]:
                    raise ValueError(f"reference_edit anchor {anchor.id!r} needs an earlier anchor")
            elif anchor.generation == "independent_t2i":
                if anchor.reference and anchor.reference not in ids[:index]:
                    raise ValueError(f"independent_t2i anchor {anchor.id!r}: continuity reference "
                                     "must be an earlier anchor")
            elif anchor.reference:
                raise ValueError(f"text_to_image anchor {anchor.id!r} cannot declare reference")
        seen_chapters: list[str] = []
        for anchor in self.anchors:
            if anchor.chapter is not None and (not seen_chapters or seen_chapters[-1] != anchor.chapter):
                if anchor.chapter in seen_chapters:
                    raise ValueError(f"chapter {anchor.chapter!r} must be contiguous")
                seen_chapters.append(anchor.chapter)
        if len(self.transitions) != len(self.anchors) - 1:
            raise ValueError("V1 transitions must exactly connect consecutive anchors")
        for i, transition in enumerate(self.transitions):
            if (transition.from_anchor, transition.to_anchor) != (ids[i], ids[i + 1]):
                raise ValueError(f"transition {i} must connect {ids[i]} -> {ids[i+1]}")
        if self.audio.bpm is None:
            raise ValueError("audio.bpm is required for duration_beats in V1")
        return self


def load_storyboard(path: str | Path) -> Storyboard:
    """Read a local YAML storyboard and validate it strictly."""
    filepath = Path(path)
    with filepath.open("r", encoding="utf-8") as stream:
        obj = yaml.safe_load(stream)
    if not isinstance(obj, dict):
        raise ValueError("storyboard must be a YAML mapping")
    return Storyboard.model_validate(obj)
