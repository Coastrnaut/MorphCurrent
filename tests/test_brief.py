"""F22 brief → editable storyboard (deterministic, offline)."""
from __future__ import annotations

import json
from pathlib import Path

import pytest
import yaml
from pydantic import ValidationError

from morph_studio import cli
from morph_studio.brief import Brief, BriefError, plan_storyboard
from morph_studio.dag import compile_plan
from morph_studio.schema import Storyboard

REPO = Path(__file__).resolve().parents[1]
PILOT = REPO / "configs/briefs/engineering-pilot.yaml"


def pilot() -> Brief:
    return Brief.model_validate(yaml.safe_load(PILOT.read_text(encoding="utf-8")))


def test_eight_scene_brief_to_valid_plan():
    data, preview = plan_storyboard(pilot())
    sb = Storyboard.model_validate(data)
    assert len(sb.anchors) == 8 and len(sb.transitions) == 7
    assert sb.anchors[0].generation == "text_to_image"
    assert all(a.generation == "reference_edit" and a.reference == sb.anchors[i].id
               for i, a in enumerate(sb.anchors[1:]))
    assert [a.id for a in sb.anchors][:3] == ["forked-lightning-bolt", "glass-leyden-jar-with-a", "voltaic-pile-of"]
    assert all(t.choreography and t.choreography.camera == "static" for t in sb.transitions)
    assert "condenses into a glowing column" in sb.transitions[0].prompt
    plan = compile_plan(sb, repo_root=REPO)
    assert sum(1 for t in plan["tasks"].values() if t["kind"] == "bridge") == 7
    assert abs(preview["anchor_span_s"] - 32) <= preview["seconds_per_bridge"]
    assert preview["unique_frames"] == plan["tasks"]["final:movie"]["unique_frames_if_endpoints_match"]
    assert plan["tasks"]["anchor:forked-lightning-bolt"]["style_pack"] == "engineering-noir@v1"


def test_deterministic():
    assert plan_storyboard(pilot()) == plan_storyboard(pilot())


def test_duration_limits():
    b = pilot().model_copy(update={"duration_s": 1.0})
    with pytest.raises(BriefError, match="minimum is"):
        plan_storyboard(b)
    b = pilot().model_copy(update={"duration_s": 300.0})  # 42.9 s per bridge > 5 s max
    with pytest.raises(BriefError, match="ladder-propose"):
        plan_storyboard(b)


def test_unsafe_or_blank_input_rejected():
    raw = yaml.safe_load(PILOT.read_text(encoding="utf-8"))
    for bad in ({"title": "../evil"}, {"title": "x" * 200}):
        with pytest.raises(ValidationError):
            Brief.model_validate({**raw, **bad})
    raw2 = dict(raw)
    raw2["scenes"] = [{"subject": "   "}, {"subject": "ok"}]
    with pytest.raises(ValidationError):
        Brief.model_validate(raw2)
    raw3 = dict(raw)
    raw3["scenes"] = [{"subject": "glass\x07 orb\n with\ttabs"}, {"subject": "copper coil"}]
    assert Brief.model_validate(raw3).scenes[0].subject == "glass orb with tabs"


def test_duplicate_subjects_get_unique_ids():
    raw = yaml.safe_load(PILOT.read_text(encoding="utf-8"))
    raw["scenes"] = [{"subject": "copper coil"}, {"subject": "copper coil"}, {"subject": "copper coil"}]
    raw["duration_s"] = 8
    data, _ = plan_storyboard(Brief.model_validate(raw))
    assert [a["id"] for a in data["anchors"]] == ["copper-coil", "copper-coil-2", "copper-coil-3"]


def test_cli_brief_plan(tmp_path, capsys):
    out = tmp_path / "pilot.yaml"
    assert cli.main(["brief-plan", str(PILOT), "--out", str(out)]) == 0
    preview = json.loads(capsys.readouterr().out)
    assert preview["bridges"] == 7 and preview["blocked"] == []
    text = out.read_text(encoding="utf-8")
    assert text.startswith("# Generated by `morphcurrent brief-plan`")
    Storyboard.model_validate(yaml.safe_load(text))
    assert cli.main(["brief-plan", str(PILOT), "--out", str(out)]) == 2  # never overwrites


def test_llm_extension_point_is_refused(tmp_path, capsys):
    out = tmp_path / "sb.yaml"
    code = cli.main(["brief-plan", str(REPO / "configs/briefs/engineering-pilot.yaml"), "--out", str(out), "--llm"])
    assert code == 2 and not out.exists()
    assert "not enabled" in capsys.readouterr().err
